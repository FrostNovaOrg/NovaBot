package com.starlwr.bot.core.model;

/**
 * 一条时间序列在本场之内的峰值
 * <p>
 * <b>为什么要在归档时算出来存下来</b>：序列本身活在本场数据里，下一次开播即清零。
 * 场次列表要显示「这一场最高多少人在看」，事后已经无处可问——
 * 峰值必须在下播那一刻从序列里取出来，随场次一起落盘。
 * <p>
 * ⚠️ <b>时刻与取值必须同源</b>：分两处各算一次，会算出「峰值 137，出现在第 42 分钟」
 * 而第 42 分钟其实是 96 的情形，且两个数各自看起来都合理。
 *
 * @param at 峰值所在时间格的起始时刻（毫秒）
 * @param value 该格的取值
 */
public record SeriesPeak(long at, double value) {
}
