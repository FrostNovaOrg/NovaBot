package com.starlwr.bot.core.timeline;

/**
 * 时间线写入口
 * <p>
 * 各处「发生了什么」的现场只依赖这一个方法，不依赖存储实现。分出这个接口有两个理由：
 * <ul>
 *   <li>现场（推送闸门、推送记录、健康告警）都是不碰磁盘的类，让它们直接拿到
 *       一个会写文件的对象，等于把它们的单元测试也变成要准备目录的测试；</li>
 *   <li>{@link #NONE} 让「不记时间线」成为一个<b>写得出来的选择</b>。
 *       换成「构造方法可以不传、不传就不记」那种写法，漏传与故意不传长得一模一样，
 *       而漏传的表现是时间线安静地少了一整类事件。</li>
 * </ul>
 */
public interface TimelineWriter {
    /**
     * 不记录任何事件的写入口
     * <p>
     * 只给测试与确实不需要时间线的调用方用。<b>生产装配里不该出现它</b>——
     * 真要有一处需要关掉时间线，那该是一个配置项，而不是在装配处换一个实现。
     */
    TimelineWriter NONE = event -> {
    };

    /**
     * 记一条事件
     * <p>
     * <b>实现必须自己吞掉一切异常。</b>调用点都在正事的主路上（推送、告警），
     * 记不下来这件事本身不该连累正事。
     * @param event 事件
     */
    void record(TimelineEvent event);
}
