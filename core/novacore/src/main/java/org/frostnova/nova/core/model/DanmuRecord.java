package org.frostnova.nova.core.model;

/**
 * 一条弹幕原文
 * <p>
 * <b>此前一条都没留。</b>弹幕到达时只做了两件事：计数、分词入词频表——
 * 前者答得出「这一场有多少条」，后者答得出「哪些词出现得多」，
 * 而「那一句到底是什么」在两者之间被丢掉了，且<b>丢得不可逆</b>：
 * 词频是分词后的结果，从「好听×37」拼不回任何一句原话。
 * <p>
 * 留原文之后能做的事，全都是此前做不到的：情绪与话题分析、按人回看某位观众说过什么、
 * 换一套分词重跑词云、把高能片段的那几分钟原样读出来。
 * <p>
 * ⚠️ <b>这份数据长期持有他人的 uid 与发言原文</b>，与 {@code sessions.jsonl} 同性质，
 * 隐私边界照 2026-08-07 那条：数据不出这个生态，脱敏留给导出层。
 * 写测试时同样<b>不许拿真实 uid 或真实弹幕当夹具</b>。
 *
 * @param at 发送时刻（毫秒）
 * @param uid 发送者 UID
 * @param uname 发送者昵称，记录当时的值——昵称会改，事后再查得到的是另一个名字
 * @param text 原文
 * @param type 类型
 */
public record DanmuRecord(long at, Long uid, String uname, String text, Type type) {
    /**
     * 弹幕的类型
     * <p>
     * <b>闭集，且刻意不按平台的消息名分</b>：这里分的是「这条发言在统计上算什么」，
     * 各平台的表情弹幕、付费留言叫法不一，但落到这三类上是一样的。
     */
    public enum Type {
        /**
         * 普通文字弹幕
         */
        DANMU,

        /**
         * 表情包弹幕。<b>与文字弹幕一同计入弹幕条数</b>，因此密度统计要把它算进来
         */
        EMOJI,

        /**
         * 付费留言（醒目留言）。<b>不计入弹幕条数</b>，密度统计须排除——
         * 把它算进弹幕密度，会让一条 30 元的留言在曲线上等价于一条「哈哈」
         */
        SUPER_CHAT
    }

    /**
     * 这一条是否计入弹幕密度
     * <p>
     * 判据写在这里一处：高能时刻按密度挑，与报告图上那条弹幕曲线必须同口径，
     * 两边各写一份的话，图上的峰与列出来的高能时刻迟早对不上。
     */
    public boolean countsAsDanmu() {
        return type == Type.DANMU || type == Type.EMOJI;
    }
}
