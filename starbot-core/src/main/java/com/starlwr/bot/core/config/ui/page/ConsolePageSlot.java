package com.starlwr.bot.core.config.ui.page;

/**
 * 插件页在控制台里挂到哪一处
 * <p>
 * 五种落位由插件自己申报：<b>核心不认识任何一个具体平台</b>，也就无从判断某一页该摆在哪儿。
 * 直播平台的账号登录属于「这台机器与外面怎么连」，因此落 {@link #LINKS}；
 * 与连接无关、也不需要独占一整页的，仍落 {@link #SETTINGS}；
 * 需要与首页／推送／主播等并列的一整页，落 {@link #TOP}；
 * 只在首页放一张卡、不占导航也没有独立地址的，落 {@link #HOME_CARD}；
 * 向导里的一步、不占导航也没有独立地址的，落 {@link #SETUP_STEP}。
 */
public enum ConsolePageSlot {
    /**
     * 连接页上的一张卡
     * <p>
     * 卡壳（标题、灯、那句状态说明）由核心按运行状态画，卡里的内容由插件自己填。
     * 分开是因为两侧知道的事不一样：核心知道「这一段此刻是好是坏」——它手里有探针与账号状态，
     * 而扫码、退出登录这些只有插件自己做得了。
     */
    LINKS,

    /**
     * 设置页「高级」折页里的一张子页
     * <p>
     * 缺省落位。与连接无关的插件页放这里，地址是 {@code #/settings/<页标识>}。
     */
    SETTINGS,

    /**
     * 与首页／推送／主播／日志／连接／设置并列的一整页
     * <p>
     * 导航里有自己的入口，地址是 {@code #/<页标识>}。
     * 标识不得与内置页名撞车，撞了不予登记。
     */
    TOP,

    /**
     * 首页一张卡，不占导航、无独立地址
     */
    HOME_CARD,

    /**
     * 向导里的一步，不占导航、无独立地址
     */
    SETUP_STEP
}
