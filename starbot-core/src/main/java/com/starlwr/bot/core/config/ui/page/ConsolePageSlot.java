package com.starlwr.bot.core.config.ui.page;

/**
 * 插件页在控制台里挂到哪一处
 * <p>
 * 控制台的六页导航是按「使用者此刻想干什么」划分的，插件带来的东西也得落进那六页里，
 * 而不是各自另开一页——每装一个插件多一个顶级入口，导航就退回了「按谁提供的」分类，
 * 那正是六页导航要解决的问题。
 * <p>
 * 落位由插件自己申报：<b>核心不认识任何一个具体平台</b>，也就无从判断某一页该摆在哪儿。
 * 直播平台的账号登录属于「这台机器与外面怎么连」，因此落 {@link #LINKS}；
 * 与连接无关的那些仍落 {@link #SETTINGS}。
 */
public enum ConsolePageSlot {
    /**
     * 连接页上的一张卡
     * <p>
     * 卡壳（标题、灯、那句状态说明）由核心按运行状态画，卡里的内容由插件自己填。
     * 分开是因为两侧知道的事不一样：核心知道「这一段此刻是好是坏」——它手里有探针与账号状态，
     * 而扫码、退出登录这些只有插件自己做得了。
     */
    LINKS,

    /**
     * 设置页「高级」折页里的一张子页
     * <p>
     * 缺省落位。与连接无关的插件页放这里，地址是 {@code #/settings/<页标识>}。
     */
    SETTINGS
}
