/**
 * 各页签共享的可变状态。
 *
 * 为什么要装进一个对象而不是各自 export 一个 let：ES module 的导入是**只读绑定**，
 * `import { tab }` 之后再 `tab = 'push'` 会直接抛 TypeError。挂在对象上改属性则不受限，
 * 也让「这是跨页签共享的东西」在读代码时一眼可见——散落的裸全局做不到这一点。
 */
export const store = {
  /** 配置项字段表，按设置页的八个组组织，来自编译期生成的元数据 */
  schema: [],
  /**
   * 一条分组前缀也匹配不上的配置项，来自 /schema
   *
   * 正常情况下它是空的——构建期那道判据会先红。留这一栏是为了让「有项没归组」这件事
   * 在跑起来的程序上也看得见：把它们并进某个「其他」组的话，界面照样显示得好好的，
   * 而没有任何东西会再提起这件事
   */
  ungrouped: [],
  /** application.yml 里的当前值 */
  values: {},
  /**
   * 按旧位置生效的配置项：现行键 → 它实际生效的那个旧键，来自 /values
   *
   * 配置键改过名，而既有部署的 application.yml 里写的还是旧位置。值本身已由服务端按
   * 「现行键优先、现行键没写到的项才落回旧位置」补进 values，这张表只回答
   * 「这一项是从哪一行读来的」——不标出来的话，界面上的值在文件里找不到对应的行，
   * 使用者会以为界面在乱显示，或是改了另一处却不生效
   */
  legacy: {},
  /** 设置页尚未保存的改动 */
  dirty: {},
  /**
   * 配置项名 → 生效时机（IMMEDIATE / RESTART），由 /schema 现算
   *
   * 后端对没标注的项回 null，这里原样存着而不是在收进来的时候补成 RESTART：
   * 补了之后「这一项没人标过」就再也看不出来，而按需重启显示只是显示上的兜底
   */
  effects: {},
  /**
   * 保存过、仍要等重启才生效的配置项，来自 /status
   *
   * 由服务端给而不是界面自己攒：这条提示的寿命是「到下次重启为止」，而只有服务端知道
   * 自己是不是刚起来的。界面自己记的话，重启完那条提示还挂着，得有人手动点掉
   */
  restartPending: [],
  /** 当前页签 */
  tab: 'overview',
  /** 写请求要带的 CSRF 令牌，登录后由 /auth/state 下发 */
  csrfToken: '',
  /** datasource.json 解析结果，改动直接作用其上以保留表单未覆盖的字段 */
  pushData: [],
  /**
   * 上一次载入时的推送配置快照，序列化后的字符串
   *
   * 底部改动条要答「改了几处」，而推送页的改动是直接落在 pushData 上的，没有逐项记账。
   * 拿它与快照比即可现算出条数。存序列化后的字符串而不是对象引用：存引用的话，
   * 它与 pushData 指向同一批对象，改动会同时反映到「快照」上——那时两边永远相等，
   * 改动条恒显示 0，而这件事在界面上看不出任何异常
   */
  pushSaved: '[]',
  /** 已注册的推送处理器 */
  handlerList: [],
  /** 已配置的机器人平台 */
  senderList: [],
  /** 全局推送开关的当前状态 */
  pushEnabled: true,
  /** 扫码登录的轮询计时器 */
  accountTimer: null,
  /**
   * 已注册数据源服务的直播平台，来自 /platforms
   *
   * 空着就是一个直播平台插件都没装。此时添加主播这件事根本做不成，界面要当场说明白，
   * 而不是替使用者猜一个平台名填进去——猜得对不对，要等到查询失败那一刻才知道
   */
  platforms: [],
  /**
   * 当前是否真的需要动态验证码，来自 /auth/state
   *
   * 「配置里开了二次验证」与「此刻真的要输验证码」不是一回事——验证器还没绑时就不要。
   * 界面必须照这一位来显示验证码框，否则说明文字与服务端的实际要求就会各说各话
   */
  totpRequired: false,
  /**
   * 配置文件在不在，来自 /auth/state 的 setupDone
   *
   * 三态而不是布尔：null 是「还没问到」。进首页该不该转到初始设置不看这一位，
   * 看五步完成了 0 步（home-model 的 shouldOpenSetup）。同意协议就会写出配置文件，
   * 按这一位跳的话刚装好的机器会停在空首页。
   */
  setupDone: null,
};
